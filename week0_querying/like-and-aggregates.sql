-- ПОШУК ПІДРЯДКА: LIKE та %
-- = шукає точний збіг усього рядка
-- LIKE дозволяє шаблон, % означає "будь-який текст"

SELECT title FROM books WHERE title LIKE 'The%';    -- починається на The
SELECT title FROM books WHERE title LIKE '%end';    -- закінчується на end
SELECT title FROM books WHERE title LIKE '%love%';  -- love будь-де всередині

-- УВАГА: LIKE знайде послідовність літер навіть усередині довшого слова.
-- '%art%' знайде і "art", і "Sparta", і "particle".

-- РЕГІСТР
-- У SQLite LIKE для латиниці регістр ІГНОРУЄ:
-- '%capital%', '%Capital%', '%CAPITAL%' дадуть однаковий результат.
-- А от = регістр ВРАХОВУЄ завжди:
--   author = 'hokusai'  поверне 0 рядків
--   author = 'Hokusai'  поверне всі потрібні
-- У PostgreSQL навпаки: LIKE чутливий до регістру, для нечутливого є ILIKE.

-- ДВІ УМОВИ РАЗОМ
SELECT title FROM books WHERE author = 'King' AND year > 1990;

-- АГРЕГАТНІ ФУНКЦІЇ: стискають усі рядки в один результат
SELECT COUNT(*) FROM books;            -- скільки рядків
SELECT MAX(pages) FROM books;          -- найбільше значення
SELECT MIN(pages) FROM books;          -- найменше значення
SELECT AVG(pages) FROM books;          -- середнє

-- ВКЛАДЕННЯ ФУНКЦІЙ: читається зсередини назовні
-- спочатку AVG рахує середнє, потім ROUND округлює результат
SELECT ROUND(AVG(pages), 2) FROM books;
-- ROUND це функція, вона живе в SELECT, а не в кінці запиту

-- ПЕРЕЙМЕНУВАННЯ КОЛОНКИ: AS
SELECT MAX(pages) AS "Maximum Pages" FROM books;
-- одинарні лапки  = текстове ЗНАЧЕННЯ ('King')
-- подвійні лапки  = ІМʼЯ колонки з пробілами ("Maximum Pages")

-- СОРТУВАННЯ ТА ОБМЕЖЕННЯ
SELECT title FROM books ORDER BY pages DESC LIMIT 5;  -- від більшого
SELECT title FROM books ORDER BY pages ASC LIMIT 5;   -- від меншого
-- ASC це поведінка за замовчуванням, але краще писати явно
-- сортувати можна по колонці, якої немає в SELECT

-- ЖОРСТКИЙ ПОРЯДОК ЧАСТИН ЗАПИТУ
-- SELECT ... FROM ... WHERE ... ORDER BY ... LIMIT ...
-- місцями міняти не можна

-- МАКСИМУМ РАЗОМ З ІНШОЮ КОЛОНКОЮ
-- НЕ так: SELECT title, MAX(pages) FROM books;
--   MAX стискає всі рядки в один, а title належить конкретному рядку.
--   Помилки не буде, але рядок може повернутись не той.
-- А так:
SELECT title, author FROM books ORDER BY pages DESC LIMIT 1;

