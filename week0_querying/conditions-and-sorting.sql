-- Приклади на узагальненій таблиці people:
--   first_name, last_name   текст
--   hand                    текст, одна літера R або L
--   height, weight          числа
--   start_date, end_date    дати у форматі YYYY-MM-DD
--   birth_country           текст, може бути NULL


-- ------------------------------------------------------------
-- УМОВИ У WHERE
-- ------------------------------------------------------------

-- Кожна умова це ПОВНЕ порівняння: колонка, оператор, значення.
-- Одна умова перевіряє ОДНУ колонку.
-- Не можна в одному порівнянні перевірити два значення.

-- НЕ так: WHERE hand ('L' AND 'R')
-- А так:
SELECT first_name, last_name FROM people WHERE hand = 'R';

-- Перевірка себе: закрити рукою все зліва від AND.
-- Те, що справа, має виглядати як завершена умова.
-- Якщо там просто 'R', значить порівняння пропущено.


-- ЗАПЕРЕЧЕННЯ: != або <>, працюють однаково
SELECT first_name, last_name FROM people WHERE birth_country != 'USA';


-- ------------------------------------------------------------
-- ПРІОРИТЕТ AND НАД OR
-- ------------------------------------------------------------

-- AND виконується раніше за OR, як множення раніше за додавання.
-- Запит нижче база згрупує як (A AND B) OR (C AND D):

SELECT COUNT(*) FROM people
WHERE hand = 'L' AND height > 180 OR hand = 'R' AND height > 190;

-- Результат правильний, але покладатись на пріоритет ризиковано.
-- ПРАВИЛО: є і AND, і OR в одному WHERE, значить є ДУЖКИ.

SELECT COUNT(*) FROM people
WHERE (hand = 'L' AND height > 180)
   OR (hand = 'R' AND height > 190);

-- Це не вимога синтаксису, це захист від власних помилок.
-- Помилка в групуванні не викличе повідомлення,
-- база просто мовчки поверне інші дані.


-- ------------------------------------------------------------
-- СОРТУВАННЯ ЗА КІЛЬКОМА КОЛОНКАМИ
-- ------------------------------------------------------------

-- Колонки перелічуються через КОМУ.
-- Порядок перелічення задає пріоритет: спочатку за першою,
-- а рядки з однаковим значенням впорядковуються за другою.

SELECT first_name, last_name FROM people
ORDER BY first_name, last_name;

-- НАПРЯМОК задається для КОЖНОЇ колонки окремо.
-- DESC після першої не поширюється на наступні.

SELECT first_name, last_name, start_date FROM people
ORDER BY start_date DESC, first_name, last_name;
-- дата за спаданням, імена за зростанням

-- Кома потрібна навіть після DESC:
-- ORDER BY start_date DESC first_name   синтаксична помилка

-- ORDER BY без колонки не працює:
-- ORDER BY DESC                          синтаксична помилка
-- DESC це лише напрямок, база має знати, ЩО сортувати.


-- ------------------------------------------------------------
-- NULL ПРИ СОРТУВАННІ
-- ------------------------------------------------------------

-- У SQLite NULL вважається найменшим значенням,
-- тому при DESC такі рядки опиняються в кінці.
-- У PostgreSQL за замовчуванням навпаки.
-- Ще один діалектний нюанс, який ламає перенесені запити.


-- ------------------------------------------------------------
-- ДАТИ І BETWEEN
-- ------------------------------------------------------------

-- BETWEEN завжди в парі з AND, обидві межі включно.
SELECT first_name, last_name FROM people
WHERE end_date BETWEEN '2022-01-01' AND '2022-12-31'
ORDER BY first_name, last_name;

-- Те саме двома умовами:
SELECT first_name, last_name FROM people
WHERE end_date >= '2022-01-01' AND end_date <= '2022-12-31';

-- IS з BETWEEN не вживається.
-- IS BETWEEN ...   помилка, IS тільки з NULL.

-- Дата в умові ОБОВʼЯЗКОВО в одинарних лапках:
SELECT ROUND(AVG(height), 2) AS "Average Height"
FROM people
WHERE start_date >= '2000-01-01';


-- ------------------------------------------------------------
-- ДЕ СТАВИТЬСЯ AS
-- ------------------------------------------------------------

-- AS ставиться ПІСЛЯ повністю завершеного виразу,
-- коли всі дужки вже закриті.
-- Всередині дужок функції можуть бути тільки АРГУМЕНТИ.

-- НЕ так: ROUND(AVG(height) AS "Average Height", 2)
-- А так:
SELECT ROUND(AVG(height), 2) AS "Average Height",
       ROUND(AVG(weight), 2) AS "Average Weight"
FROM people;

-- ПРАВИЛО: AS завжди останнє в елементі SELECT.
-- Спершу обчислення, потім назва.


-- ------------------------------------------------------------
-- РОЗВІДКА ДАНИХ ПЕРЕД НАПИСАННЯМ УМОВИ
-- ------------------------------------------------------------

-- Показує, які взагалі значення бувають у колонці.
SELECT DISTINCT hand FROM people;


