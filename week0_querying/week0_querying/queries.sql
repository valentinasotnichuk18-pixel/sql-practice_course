-- 1. NULL це не нуль і не порожній рядок, це ВІДСУТНІСТЬ значення.
--
-- NULL ні з чим не порівнюється, навіть сам із собою. Логіка SQL
-- тризначна: TRUE, FALSE, UNKNOWN. WHERE пропускає тільки TRUE,
-- тому UNKNOWN відкидається разом із FALSE.
--
-- Перевірено на даних:
--   всього книг                          78
--   translator = 'Frank Wynne'            3
--   translator != 'Frank Wynne'          73
--   3 + 73 = 76, а не 78
-- Дві книги з NULL не потрапили НІ в "дорівнює", НІ в "не дорівнює".
--
-- Правильний варіант:
SELECT COUNT(*) FROM longlist
WHERE translator != 'Frank Wynne' OR translator IS NULL;
-- дає 75, і 75 + 3 = 78
--
-- ВИСНОВОК ДЛЯ QA: у будь-якому тест-кейсі на фільтр обовʼязково
-- мають бути дані з NULL. Реальний сценарій бага: фільтр
-- "показати всі замовлення, крім скасованих" через
-- WHERE status != 'cancelled' тихо викидає замовлення,
-- де статус ще не проставлений.


-- 2. Робота з незнайомою базою починається зі схеми і даних.
--
-- .schema                          структура таблиць
-- SELECT * FROM таблиця LIMIT 5;   як реально виглядають значення
--
-- Не писати запити, поки не побачив дані. Опис у документації
-- може не збігатися з тим, що в базі насправді.


-- 3. Кількість рядків це перша перевірка правильності.
--
-- COUNT(*) дає число, яке легко порівняти з очікуваним.
-- Але збіг кількості рядків не означає, що запит правильний:
-- він міг дати вірне число випадково, на конкретних даних.
-- Запит має відповідати УМОВІ, а не підганятись під результат.


-- 4. Дублікати в результаті це привід зупинитись.
--
-- У базі cyberchase 140 записів, але тільки 136 унікальних назв.
-- Побачив повтор, перевір, чи так задумано.
-- Половина багів у звітах це задвоєні рядки, яких ніхто не помітив.


-- 5. Різниця діалектів ламає перенесені запити.
