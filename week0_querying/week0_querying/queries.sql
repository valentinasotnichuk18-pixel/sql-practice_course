-- ПОМИЛКА 1. Пропущений оператор після WHERE
-- WHERE author 'Han Kang'         неправильно
-- WHERE author = 'Han Kang'       правильно
-- Умова завжди: колонка, оператор, значення. Пропуск середньої
-- частини це найчастіша синтаксична помилка на старті.


-- ПОМИЛКА 2. Подвійні лапки замість одинарних
-- WHERE author = "Han Kang"       помилка: no such column
-- WHERE author = 'Han Kang'       правильно
-- Подвійні лапки = назва колонки або таблиці
-- Одинарні лапки = текстове значення
-- ВАЖЛИВО: у MySQL подвійні лапки часто працюють як одинарні,
-- тому запит з MySQL може впасти при переносі в SQLite чи Postgres.


-- ПОМИЛКА 3. Забута крапка з комою
-- Якщо в терміналі замість sqlite> зʼявилось ...>
-- це завжди означає незакриту команду:
-- забута крапка з комою, незакрита дужка або незакрита лапка.
-- Вихід: Ctrl+C або дописати ;


-- ПОМИЛКА 4. Плутанина колонки і таблиці
-- SELECT episode FROM season      неправильно
-- season це КОЛОНКА, а не таблиця
-- Після FROM завжди назва таблиці, після SELECT назви колонок зі схеми.


-- ПОМИЛКА 5. Виводжу колонку, за якою фільтрую
-- SELECT season FROM episodes WHERE season = 1
-- поверне 26 однакових одиниць, а не список серій
-- SELECT title FROM episodes WHERE season = 1
-- ось це список серій


-- ПОМИЛКА 6. LIKE без лапок
-- WHERE title LIKE %love%         синтаксична помилка
-- WHERE title LIKE '%love%'       правильно
-- Шаблон це текст, тому в одинарних лапках, разом із символами %


-- ПОМИЛКА 7. LIKE без колонки
-- WHERE LIKE '%multi%'            неправильно, немає лівої сторони
-- WHERE topic LIKE '%multi%'      правильно


-- ПОМИЛКА 8. IS замість =
-- WHERE title IS 'Hackerized!'    у SQLite працює, але це не стандарт
-- WHERE title = 'Hackerized!'     правильно
-- IS використовується ТІЛЬКИ з NULL: IS NULL, IS NOT NULL
-- У PostgreSQL і MySQL перший варіант впаде з помилкою.


-- ПОМИЛКА 9. Порівняння тексту з числом
-- WHERE air_date < 2008           текст порівнюється з числом
-- WHERE air_date < '2008-01-01'   правильно
-- Дати в SQLite зберігаються як текст YYYY-MM-DD.
-- Такий формат сортується правильно як звичайний текст, бо рік перший.
-- Найнебезпечніше тут те, що база НЕ падає з помилкою,
-- вона тихо повертає непередбачуваний результат.


-- ПОМИЛКА 10. Переставлені цифри в даті
-- '2004-12-13' це 13 грудня, а не 31 грудня
-- Формат YYYY-MM-DD: рік, місяць, день


-- ПОМИЛКА 11. Опечатка в значенні дає тихий нуль
-- WHERE air_date BETWEEN '202-01-01' AND '2007-12-31'
-- поверне 0 і НЕ покаже жодної помилки
-- Порожній результат це не відповідь, а привід перевірити:
--   1) чи правильно написані значення в умові
--   2) чи справді таких даних немає
--   3) чи не заважає NULL


-- ПОМИЛКА 12. Обрізаний діапазон, off by one
-- BETWEEN '2018-01-01' AND '2023-01-01'   загубить майже весь 2023
-- BETWEEN '2018-01-01' AND '2023-12-31'   правильно
-- Різниця на моїх даних була 27 проти 31, чотири втрачені записи.


