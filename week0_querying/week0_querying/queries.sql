-- ------------------------------------------------------------
-- ПОРЯДОК ЧАСТИН ЗАПИТУ
-- Порядок фіксований, поміняти місцями не можна
--
--   SELECT   які колонки показати
--   FROM     з якої таблиці
--   WHERE    які рядки залишити
--   ORDER BY як відсортувати
--   LIMIT    скільки рядків вивести
--
-- Ключове: після SELECT іде те, що хочу ПОБАЧИТИ,
-- після WHERE іде те, за чим ФІЛЬТРУЮ. Це різні колонки.
-- ------------------------------------------------------------


-- SELECT: вибір конкретних колонок
-- SELECT * тягне всі колонки, на широкій таблиці нечитабельно
SELECT title, author FROM longlist;


-- LIMIT: обмежити кількість рядків
SELECT title, author FROM longlist LIMIT 10;


-- WHERE: фільтрація за умовою
-- Умова завжди з трьох частин: колонка, оператор, значення
SELECT title, author FROM longlist WHERE author = 'Han Kang';


-- COUNT: база рахує рядки замість мене
-- AS: аліас, змінює тільки заголовок у виводі
SELECT COUNT(*) AS books_over_500 FROM longlist WHERE pages > 500;


-- IS NULL: пошук відсутніх значень
SELECT title FROM longlist WHERE translator IS NULL;


-- LIKE: пошук за частиною тексту
-- %  будь-яка кількість будь-яких символів
-- _  рівно один будь-який символ
SELECT title FROM longlist WHERE title LIKE '%Love%';


-- DISTINCT: тільки унікальні значення
SELECT DISTINCT publisher FROM longlist;


-- COUNT(DISTINCT ...): скільки різних значень у колонці
SELECT COUNT(DISTINCT author) FROM longlist;


-- BETWEEN: діапазон, ОБИДВІ межі включно
SELECT title FROM longlist WHERE pages BETWEEN 100 AND 200;


-- AND / OR: складені умови
SELECT title FROM longlist WHERE year = 2023 AND pages > 500;


-- ORDER BY: сортування
-- за замовчуванням ASC (зростання), DESC для зворотного
SELECT title, rating FROM longlist ORDER BY rating DESC;


