-- ============================================================
-- 1. НАВІЩО ПОТРІБЕН JOIN
-- ============================================================

-- Дані розкидані по різних таблицях. Текст (назви, імена, адреси)
-- живе тільки в довідникових таблицях. У таблицях-звʼязках лише числа.
-- JOIN склеює таблиці в одну тимчасову, щоб дістати все разом.

-- Ключова пара понять:
--   id            власний номер рядка в цій таблиці (PK)
--   щось_id       номер рядка в ІНШІЙ таблиці (FK), це і є "місток"

-- Місток завжди впізнається за назвою: у ній сидить чужа таблиця.
--   schools.district_id        -> місток на districts
--   expenditures.district_id   -> місток на districts
--   graduation_rates.school_id -> місток на schools


-- ============================================================
-- 2. БАЗОВИЙ СИНТАКСИС
-- ============================================================

-- Формула, яка не змінюється ніколи:
--   JOIN назва_таблиці ON таблиця.id = друга_таблиця.таблиця_id
--
-- Після JOIN завжди НАЗВА ТАБЛИЦІ.
-- Після ON завжди ДВА ЧИСЛОВІ СТОВПЦІ.

SELECT districts.name, expenditures.per_pupil_expenditure
FROM districts
JOIN expenditures
ON districts.id = expenditures.district_id;

-- Бік у ON не має значення, знак рівності працює в обидва боки:
--   districts.id = expenditures.district_id
--   expenditures.district_id = districts.id
-- Обидва варіанти правильні.

-- ВАЖЛИВО: обидві назви таблиць у ON мають бути серед тих,
-- що стоять після FROM і після JOIN. Якщо в ON зʼявилася назва
-- нізвідки, це помилка.


-- ============================================================
-- 3. ДВА JOIN В ОДНОМУ ЗАПИТІ
-- ============================================================

-- Формула просто повторюється. FROM буває РІВНО ОДИН РАЗ,
-- далі йдуть лише JOIN, скільки завгодно.

SELECT schools.name, expenditures.per_pupil_expenditure, graduation_rates.graduated
FROM schools
JOIN graduation_rates
ON graduation_rates.school_id = schools.id
JOIN expenditures
ON expenditures.district_id = schools.district_id;

-- Правило: КІЛЬКІСТЬ JOIN = КІЛЬКІСТЬ ТАБЛИЦЬ МІНУС ОДИН.
--   2 таблиці -> 1 JOIN
--   3 таблиці -> 2 JOIN


-- ============================================================
-- 4. ДВА ВИПАДКИ ДЛЯ ON (третього немає)
-- ============================================================

-- ВИПАДОК А. Між таблицями є прямий звʼязок.
-- В ON стоять id однієї таблиці і місток другої.

--   districts.id = expenditures.district_id
--   schools.id   = graduation_rates.school_id

-- ВИПАДОК Б. Прямого звʼязку немає, але обидві таблиці
-- звисають з однієї спільної. Тоді склеюємо через їхні
-- ОДНАКОВІ містки.

--   schools.district_id = expenditures.district_id

-- Випадок Б був у 11.sql: між schools і expenditures прямої
-- стрілки немає, але обидві висять під districts. Таблиця
-- districts у запиті при цьому взагалі не потрібна,
-- бо номер округу вже лежить всередині schools.


-- ============================================================
-- 5. МЕТОД ТРЬОХ КРОКІВ (як визначити таблиці)
-- ============================================================

-- Не питай "яку таблицю приєднати". Питай "де лежать слова з умови".
-- Таблиці визначає умова, а не я.

-- КРОК 1. Виписати з умови два списки:
--   що показати у результаті     -> майбутній SELECT
--   за чим фільтрувати/сортувати -> майбутні WHERE і ORDER BY

-- КРОК 2. Біля кожного слова написати таблицю, де воно лежить.
--   назва школи         -> schools
--   витрати на учня     -> expenditures
--   відсоток випускників-> graduation_rates
-- Скільки різних таблиць вийшло, стільки і буде в запиті.
-- Нічого зайвого, нічого пропущеного.

-- КРОК 3. Стартова таблиця у FROM це та, чий стовпець стоїть
-- ПЕРШИМ у SELECT. Решта чіпляються через JOIN по містках.


-- ============================================================
-- 6. КОЛИ ПОТРІБЕН WHERE
-- ============================================================

-- Правило одне: WHERE потрібен тільки якщо в умові є
-- ОБМЕЖУВАЛЬНЕ СЛОВО.

-- Обмежувальні слова: "державні", "чартерні", "з назвою Cambridge",
-- "які повідомили 100%", "3 і менше", "більше за середнє".
-- Вони відкидають частину рядків.

-- Якщо в умові "всі" або про відбір не йдеться, WHERE НЕМАЄ.

-- НЕ ПЛУТАТИ: ORDER BY і LIMIT не є фільтром. Вони не викидають
-- рядки за ознакою, а лише впорядковують і обрізають.
-- "10 найдорожчих" = ORDER BY + LIMIT, а не WHERE.


-- ============================================================
-- 7. ПІДЗАПИТ У WHERE
-- ============================================================

-- Коли порівнюємо не з готовим числом, а з середнім, яке ще
-- треба порахувати. Замість числа ставимо в дужках окремий запит.

-- SQL спершу виконує те, що в дужках, отримує ОДНЕ число,
-- підставляє його на це місце і далі працює як зі звичайним числом.

SELECT districts.name, expenditures.per_pupil_expenditure, staff_evaluations.exemplary
FROM districts
JOIN expenditures
ON expenditures.district_id = districts.id
JOIN staff_evaluations
ON staff_evaluations.district_id = expenditures.district_id
WHERE districts.type = 'Public School District'
AND expenditures.per_pupil_expenditure > (
    SELECT AVG(per_pupil_expenditure) FROM expenditures
)
AND staff_evaluations.exemplary > (
    SELECT AVG(exemplary) FROM staff_evaluations
)
ORDER BY staff_evaluations.exemplary DESC,
         expenditures.per_pupil_expenditure DESC;

-- Підзапит це повноцінний окремий запит. Він ОБОВʼЯЗКОВО
-- мусить мати свій власний FROM.
--   ПРАВИЛЬНО: (SELECT AVG(pupils) FROM expenditures)
--   ПОМИЛКА:   (SELECT AVG(pupils))

-- Кожні дві сусідні умови у WHERE зʼєднуються словом AND.


-- ============================================================
-- 8. ПОДВІЙНЕ СОРТУВАННЯ
-- ============================================================

-- Пишеться в ОДНОМУ ORDER BY через кому, а не двома рядками.
-- Спочатку головніший критерій, потім другорядний.
-- DESC діє тільки на той стовпець, після якого стоїть.

ORDER BY expenditures.per_pupil_expenditure DESC, schools.name;

-- ASC можна не писати, зростаюче сортування стоїть за замовчуванням.

-- Сортувати можна за стовпцем, якого немає у SELECT.
-- ORDER BY бачить усі стовпці приєднаних таблиць.
-- Так працює пошук мінімуму:
--   SELECT districts.name ... ORDER BY expenditures.pupils LIMIT 1;


-- ============================================================
-- 9. AS ДЛЯ ОДНАКОВИХ НАЗВ
-- ============================================================

-- Коли в результат потрапляють два стовпці з однаковою назвою
-- (schools.name і districts.name), у виводі буде два заголовки
-- "name" і зрозуміти, де що, неможливо. Лікується через AS.

SELECT schools.name AS "School", districts.name AS "District", graduation_rates.dropped
FROM schools
JOIN districts ON districts.id = schools.district_id
JOIN graduation_rates ON graduation_rates.school_id = schools.id
ORDER BY graduation_rates.dropped DESC
LIMIT 10;

-- AS міняє тільки підпис у результаті, на дані не впливає.


