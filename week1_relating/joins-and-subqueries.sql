-- 10. ПОРЯДОК КЛАУЗ (не міняється ніколи)
-- ============================================================

--   SELECT
--   FROM
--   JOIN ... ON
--   WHERE
--   GROUP BY
--   HAVING
--   ORDER BY
--   LIMIT
--   ;   <- крапка з комою ОДИН раз, у самому кінці


-- ============================================================
-- 11. ПОМИЛКИ, ЯКІ Я ЗРОБИЛА НА DESE
-- ============================================================

-- СТРУКТУРНІ

-- 1. JOIN без назви таблиці і без ON:
--      JOIN districts.id = expenditures.district_id
--    Пропущено і назву таблиці, і слово ON.

-- 2. Приєднала таблицю до самої себе:
--      FROM districts
--      JOIN districts
--    Друга таблиця так і не зʼявилася в запиті.

-- 3. В ON послалася на таблицю, якої в запиті немає:
--      FROM districts JOIN expenditures
--      ON districts.id = schools.district_id
--    Таблиці schools тут немає ні у FROM, ні у JOIN.

-- 4. Другий FROM посеред запиту. FROM буває один раз.

-- 5. Крапка з комою після ON, посеред запиту.
--    Все нижче стало окремою командою, ORDER BY і LIMIT
--    у запит не потрапили.

-- ТАБЛИЦЯ ЗАМІСТЬ СТОВПЦЯ (4 рази в одному запиті)

-- 6. WHERE expenditures > (...)
--    ORDER BY staff_evaluations DESC
--    SELECT AVG(...) без конкретного стовпця
--    Таблицю не можна порівняти з числом і не можна за нею сортувати.
--    ТАБЛИЦЯ СТОЇТЬ ТІЛЬКИ ПІСЛЯ FROM І ПІСЛЯ JOIN. Більше ніде.

-- НЕ ТОЙ СТОВПЕЦЬ

-- 7. ON graduation_rates.id = schools.id
--    Взяла власний id замість містка school_id.
--    id ні на що не вказує назовні, склеювати треба через місток.

-- 8. schools_id замість schools.id
--    Підкреслення це частина назви стовпця.
--    Крапка це "візьми з цієї таблиці". Різні речі.

-- СИНТАКСИС

-- 9.  Подвійні лапки для тексту: type = "Public School District"
--     Подвійні лапки означають НАЗВУ СТОВПЦЯ. Для тексту одинарні.

-- 10. Немає AND між умовами у WHERE.

-- 11. Підзапит без власного FROM.

-- 12. Зайва кома після єдиного стовпця: SELECT districts.name,
--     Кома розділяє стовпці. Один стовпець - коми немає.

-- ОПЕЧАТКИ (усі з памʼяті, а не з .schema)

-- 13. expentitures, per_pupil_expenditures (зайва s),
--     examplary замість exemplary, expenditure замість expenditures,
--     OREDER замість ORDER.
--     Коли пишу стовпець вдруге, треба дивитися, як він написаний
--     вище у моєму ж запиті.

-- ТИХІ БАГИ (помилки немає, відповідь неправильна)

-- 14. WHERE type = 'Public Schools'
--     Такого значення в базі немає. Запит виконався,
--     повернув порожньо, зовні виглядало нормально.
--     Перед фільтром завжди: SELECT DISTINCT type FROM districts;

-- 15. LIMIT 10, забутий у 1.sql з чернетки.
--     Замість 1761 рядка повертав 10.

