-- ============================================================
-- 12. КЛЮЧОВІ ВИСНОВКИ
-- ============================================================

-- 1. Таблиця стоїть тільки після FROM і після JOIN.
--    У WHERE, ORDER BY і всередині AVG() стоять ТІЛЬКИ стовпці.

-- 2. Кількість JOIN = кількість таблиць мінус один.
--    Таблиці диктує умова, а не моя інтуїція.

-- 3. Місток це стовпець, у назві якого сидить чужа таблиця.
--    Склеювати можна тільки через містки.

-- 4. WHERE тільки за наявності обмежувального слова.
--    ORDER BY і LIMIT це не фільтр.

-- 5. Назви стовпців і значення для WHERE копіюю з .schema
--    або з SELECT DISTINCT, ніколи з памʼяті.

